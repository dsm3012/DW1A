SELECT EM.FIRST_NAME AS EMPLEADO, MA.FIRST_NAME AS MANAGER
FROM EMPLOYEES EM
INNER JOIN EMPLOYEES MA
ON EM.MANAGER_ID=MA.EMPLOYEE_ID;

