--ADELANTO DE CONSULTA COMPLEJA BUSCANDO DATOS EN DOS TABLAS
--GRACIAS A SU RELACIÓN CON FOREIGN KEY Y PRIMARY KEY

--OBTENER NOMBRE DE EMPLEADOS Y SU NOMBRE DE DEPARTAMENTO
SELECT E.FIRST_NAME, D.DEPARTMENT_NAME
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;


