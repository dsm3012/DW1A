DESCRIBE EMPLOYEES;
--sueldos de empleados y su nombre
SELECT FIRST_NAME, SALARY FROM EMPLOYEES;

--sueldos de empleados (y su nombre) que ganen mas de 10000
SELECT FIRST_NAME, SALARY FROM EMPLOYEES WHERE SALARY > 10000;

--sueldos de empleados y su nombre que ganen menos de 10000 y mas de 6000 (ordenados order by campo asc ó desc)
SELECT FIRST_NAME, SALARY FROM EMPLOYEES WHERE SALARY <= 10000 AND SALARY >= 6000;

SELECT FIRST_NAME, SALARY FROM EMPLOYEES WHERE SALARY BETWEEN 6000 AND 10000;
--seleccionar nombre y fecha de alta de empleados
SELECT FIRST_NAME, HIRE_DATE FROM EMPLOYEES;
--empleados de alta en 2005 o después de ese año
SELECT FIRST_NAME, HIRE_DATE FROM EMPLOYEES WHERE HIRE_DATE >= '01-01-2005' ORDER BY HIRE_DATE DESC;
--USANDO EXTRACT YEAR FROM UNA FECHA
SELECT FIRST_NAME, HIRE_DATE FROM EMPLOYEES WHERE EXTRACT(YEAR FROM HIRE_DATE)>=2005; 

