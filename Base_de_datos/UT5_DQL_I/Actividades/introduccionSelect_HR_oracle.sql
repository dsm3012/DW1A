--CLÁUSULA IN, POR EJEMPLO EN WHERE
-- OBTENNER NOMBRE Y SALARIO DE EMPLEADOS CUYO SALARIO SEA 7000 10000 12000
-- CUANDO ES UN CONJUNTO LIMITADO DE VALORES USAMOS IN
