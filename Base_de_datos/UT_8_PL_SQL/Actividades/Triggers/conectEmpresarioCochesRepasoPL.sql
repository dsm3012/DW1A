--ACTUALIZAR FECHA DE ENTRADA Y FECHA DE SALIDA POR LA FECHA ACTUAL (SYSDATE)

DECLARE
 V_DNI CONDUCIR.NIF%TYPE:='85698423O';
 V_MAT CONDUCIR.MATRICULA%TYPE:='2395-JUF';
BEGIN
--UPDATE F_SALIDA Y F_ENTRADA CON LA FECHA ACTUAL PARA EL REGISTRO ENCONTRADO POR NIF Y MATRICULA
UPDATE CONDUCIR SET F_ENTRADA=SYSDATE,F_SALIDA=SYSDATE
WHERE NIF=V_DNI AND MATRICULA=V_MAT;
END;
/

DECLARE
    v_dni   CONDUCIR.NIF%TYPE      := '85698423O';
    v_mat   CONDUCIR.MATRICULA%TYPE := '2395-JUF';
    v_filas_actualizadas NUMBER;
BEGIN
    -- Actualizar fechas de entrada y salida
    UPDATE CONDUCIR
       SET F_ENTRADA = SYSDATE,
           F_SALIDA  = SYSDATE
     WHERE NIF = v_dni
       AND MATRICULA = v_mat;

    -- Guardar cuántas filas se han actualizado
    v_filas_actualizadas := SQL%ROWCOUNT;

    -- Mostrar resultado
    DBMS_OUTPUT.PUT_LINE('Filas actualizadas: ' || v_filas_actualizadas);

    -- Confirmar cambios
    COMMIT;
END;
/


ROLLBACK;

