--trigger para que al insertar un nuevo registro en la tabla conducen
--la fecha de salida f_salida no pueda ser posterior a la fecha del día

CREATE OR REPLACE TRIGGER TR_F_SALIDA
BEFORE INSERT OR UPDATE OF F_SALIDA
ON CONDUCIR
FOR EACH ROW
BEGIN
    IF :NEW.F_SALIDA > SYSDATE THEN
    RAISE_APPLICATION_ERROR (-20001,'Fecha no válida');
    END IF;
END;
/

