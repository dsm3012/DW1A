--ACTIVIDAD TRIGGER
--CREACIÓN DE TRIGGER QUE SE DISPARE AL BORRAR UNA O VARIAS FILAS (REGISTROS) EN SALGRADE
--DE FORMA QUE SE GUARDEN LOS ANTIGUOS VALORES (GRADE, LOSAL Y HISAL)
--EN UNA TABLA LLAMADA SALGRADE_BORRADOS


--1. crear tabla con los campos que necesitemos
CREATE TABLE SALGRADE_BORRADOS (
    GRADE NUMBER,
    LOSAL NUMBER,
    HISAL NUMBER,
    FECHA_BORRADO TIMESTAMP
); 

--2. crear trigger
CREATE OR REPLACE TRIGGER TRG_SLG_DEL
AFTER DELETE ON SALGRADE
FOR EACH ROW
BEGIN
    DBMS_OUTPUT.PUT_LINE('Comprueba datos almacenados en SALGRADE_BORRADOS');
    INSERT INTO SALGRADE_BORRADOS VALUES(:OLD.GRADE, :OLD.LOSAL, :OLD.HISAL,SYSDATE);
END;
/

