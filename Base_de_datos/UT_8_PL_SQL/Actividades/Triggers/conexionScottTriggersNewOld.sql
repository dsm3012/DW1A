CREATE OR REPLACE TRIGGER TR_UP_HISAL
BEFORE UPDATE OF HISAL
ON SALGRADE
FOR EACH ROW
BEGIN

    DBMS_OUTPUT.PUT_LINE('Valores modificados:');
    DBMS_OUTPUT.PUT_LINE(:OLD.HISAL || '-->' || :NEW.HISAL);

END;
