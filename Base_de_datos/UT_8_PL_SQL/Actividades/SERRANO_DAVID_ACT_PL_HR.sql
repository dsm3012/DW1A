DECLARE
-- Primero declaramos todas las variables donde almacenaremos los campos del cursor
DEPARTMENT DEPARTMENTS.DEPARTMENT_NAME%TYPE;

EMP_ID EMPLOYEES.EMPLOYEE_ID%TYPE;
EMP_NAME VARCHAR2(35);
EMP_HDATE EMPLOYEES.HIRE_DATE%TYPE;
EMP_MANAGER VARCHAR2(35);
EMP_JOB JOBS.JOB_TITLE%TYPE;
EMP_SALARY EMPLOYEES.SALARY%TYPE;
-- Luego declaramos el cursor que usaremos para asignar valores a las variables indicando como argumento el departamento que querramos
CURSOR EMP_DEPT(DEPI DEPARTMENTS.DEPARTMENT_NAME%TYPE) IS
SELECT E.EMPLOYEE_ID,E.FIRST_NAME||' '||E.LAST_NAME AS "NOMBRE",E.HIRE_DATE,E.SALARY,J.JOB_TITLE,M.FIRST_NAME||' '||M.LAST_NAME AS "MANAGER" 
FROM EMPLOYEES E INNER JOIN JOBS J ON E.JOB_ID=J.JOB_ID 
INNER JOIN EMPLOYEES M ON E.MANAGER_ID=M.EMPLOYEE_ID 
INNER JOIN DEPARTMENTS D ON D.DEPARTMENT_ID=E.DEPARTMENT_ID 
WHERE UPPER(D.DEPARTMENT_NAME)=UPPER(DEPI);

BEGIN
-- Pedimos el departamento por entrada de teclado
DEPARTMENT := '&DEPARTAMENTO';
-- Generamos la cabecera de la tabla
