--BLOQUE 1 - TRIGGER
--TRIGGER CONTROL DDE CAMBIOS EN TABLA DEPARTMENTS

-- PRIMERO SE CREA LA TABLA QUE ALMACENARA LOS CAMBIOS DE DEPARTMENTS
CREATE TABLE DEPT_LOG (OPERATION VARCHAR2(20),HORA_REALIZADA TIMESTAMP,OLD_DEPARTMENT_ID NUMBER(4),OLD_DEPARTMENT_NAME VARCHAR2(30),OLD_MANAGER_ID NUMBER(6),OLD_LOCATION_ID NUMBER(4),NEW_DEPARTMENT_ID NUMBER(4),NEW_DEPARTMENT_NAME VARCHAR2(30),NEW_MANAGER_ID NUMBER(6),NEW_LOCATION_ID NUMBER(4));

-- LUEGO SE CREA EL TRIGGER QUE MANEJARA CADA OPERACION REALIZADA DEPARTMENTS ANTES DE QUE SE PRODUZCA
CREATE OR REPLACE TRIGGER TR_DEPT_LOG BEFORE UPDATE OR INSERT OR DELETE ON DEPARTMENTS FOR EACH ROW
BEGIN
IF INSERTING THEN
    INSERT INTO DEPT_LOG VALUES('INSERT',SYSTIMESTAMP,NULL,NULL,NULL,NULL,:NEW.DEPARTMENT_ID,:NEW.DEPARTMENT_NAME,:NEW.MANAGER_ID,:NEW.LOCATION_ID);
END IF;

IF DELETING THEN
    INSERT INTO DEPT_LOG VALUES('DELETE',SYSTIMESTAMP,:OLD.DEPARTMENT_ID,:OLD.DEPARTMENT_NAME,:OLD.MANAGER_ID,:OLD.LOCATION_ID,NULL,NULL,NULL,NULL);
END IF;

IF UPDATING THEN
    INSERT INTO DEPT_LOG VALUES('UPDATE',SYSTIMESTAMP,:OLD.DEPARTMENT_ID,:OLD.DEPARTMENT_NAME,:OLD.MANAGER_ID,:OLD.LOCATION_ID,:NEW.DEPARTMENT_ID,:NEW.DEPARTMENT_NAME,:NEW.MANAGER_ID,:NEW.LOCATION_ID);
END IF;
END;
