--BLOQUE 3 - FUNCIONES
--3. Aumento o disminuci�n de salario

-- Primero declaramos la funcion con el salario, el porcentaje deseado y un char para indicar si hay que aumentar o reducir el salario
CREATE OR REPLACE FUNCTION SAL_ALTER(SAL NUMBER,INCREASE NUMBER,INCREMENTO VARCHAR2) RETURN NUMBER IS
BEGIN
-- si el varchar incremento es igual a true entonces devolvera la suma del salario y su porcentaje
    IF UPPER(INCREMENTO) = 'TRUE'  THEN
    RETURN SAL+SAL*(INCREASE/100);
    END IF;
-- en caso contrario devolvera la resta del salario y el porcentaje 
    RETURN SAL-SAL*(INCREASE/100);
END;
/

--BLOQUE 4 - PROCEDIMIENTOS
--3.1 Hace uso de la funci�n para cambiar salario de los empleados seg�n la funci�n
--solicitar� identificador de empleado
--solicitar� porcentaje de aumento o disminuci�n de salario
--aplicar� los cambios

-- Primero declaramos el procedimiento con el id del empleado que vamos a modificar, el porcentaje y un char para indicar si es un aumento o no
CREATE OR REPLACE PROCEDURE AUMENTO(EMP_ID INTEGER,PERCENTAGE NUMBER,AUMENTO VARCHAR2)
IS
-- Luego declaramos las variables que necesitemos como el nombre y el salario original junto que el modificado (realmente no es necesario)
    OLD_SALARIO NUMBER;
    NEW_SALARIO NUMBER;
    EMP_NAME VARCHAR(30);
BEGIN
-- En este select le asignamos al nombre y al salario antiguo sus valores
    SELECT SALARY,FIRST_NAME||' '||LAST_NAME INTO OLD_SALARIO,EMP_NAME FROM EMPLOYEES WHERE EMPLOYEE_ID=EMP_ID;
-- Hacemos uso de la funcion anterior para almacenar el aumento en la variable
    NEW_SALARIO := SAL_ALTER(OLD_SALARIO,PERCENTAGE,AUMENTO);
-- Actualizamos el registro
    UPDATE EMPLOYEES SET SALARY=NEW_SALARIO WHERE EMPLOYEE_ID=EMP_ID;
-- Imprimimos un mensaje orientativo para saber que cambios se han hecho
    DBMS_OUTPUT.PUT_LINE('EL SALARIO DEL EMPLEADO '||EMP_NAME||'('||EMP_ID||') HA SIDO ACTUALIZADO DE '||OLD_SALARIO||' A '||NEW_SALARIO||' EUROS.');
-- Por ultimo aplicamos los cambios mediante un commit
    COMMIT;
END;
