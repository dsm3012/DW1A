SELECT * FROM DEPT;
DECLARE
    NUMI EMP.SAL%TYPE := &N2;
BEGIN 
            DBMS_OUTPUT.PUT_LINE(RPAD('+ ',9,' ')||RPAD('EMPNO',10,' ')||RPAD('ENAME',10,' ')||'SAL');
    FOR REC IN (SELECT EMPNO,ENAME,SAL FROM EMP WHERE SAL >= NUMI) LOOP
            
            DBMS_OUTPUT.PUT_LINE(RPAD('+',35,'  ='));
            DBMS_OUTPUT.PUT_LINE(RPAD('|',9,' ')||RPAD(REC.EMPNO,10,' ')||RPAD(REC.ENAME,10,' ')||REC.SAL);
    END LOOP;
        
END;
/

DECLARE
    NUMI DEPT.DEPTNO%TYPE := &NUMI;
    NOMBRE DEPT.DNAME%TYPE;
BEGIN
    SELECT DNAME INTO NOMBRE FROM DEPT WHERE DEPTNO=NUMI;
    DBMS_OUTPUT.PUT_LINE('EL DEPARTAMENTO CON ID '||NUMI||' TIENE COMO NOMBRE '||NOMBRE);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('NO SE HA ENCONTRADO UN DEPARTAMENTO'); 
END;
