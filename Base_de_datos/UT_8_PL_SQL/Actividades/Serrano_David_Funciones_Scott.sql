SET SERVEROUTPUT ON;
SET VERIFY OFF;

DECLARE
    N1 NUMBER (2) := 2;
    N2 NUMBER (2) := 4;
    RESULTADO NUMBER;
BEGIN
    RESULTADO:=N1+N2;
    DBMS_OUTPUT.PUT_LINE(RESULTADO);
END;
/

DECLARE
    N1 NUMBER (2) := '&N1';
    OP CHAR(1) := '&OP';
    N2 NUMBER (2) := '&N2';
    RES NUMBER;
BEGIN
    CASE OP
        WHEN '+' THEN RES := N1+N2;
        WHEN '-' THEN RES := N1-N2;
        WHEN '*' THEN RES := N1*N2;
        WHEN '/' THEN RES := N1/N2;
    END CASE;

    DBMS_OUTPUT.PUT_LINE(RES);
EXCEPTION
        WHEN ZERO_DIVIDE THEN
            DBMS_OUTPUT.PUT_LINE('NO SE PUEDE DIVIDIR ENTRE 0');
    
END;
/

DECLARE
    N1 NUMBER (5) := &N1;
    N2 NUMBER (5) := &N2;
BEGIN

    IF N1 < N2 THEN 
        DBMS_OUTPUT.PUT_LINE('N2 - N1 = '||(N2-N1));
    ELSE
        DBMS_OUTPUT.PUT_LINE('N1 - N2 = '||(N1-N2));
    END IF;
        
END;
/
