--TIPOS DE ERRORES
--1. PREDEFINIDOS (EJEMPLOS: ZERO_DIVIDE, TOO_MANY_ROWS, NO_DATA_FOUND...)
--EJEMPLO CON BLOQUE ANÓNIMO (BA):
DECLARE 
    V_FIRST EMPLOYEES.FIRST_NAME%TYPE;
    
BEGIN
    SELECT FIRST_NAME INTO V_FIRST
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = 1000;
    DBMS_OUTPUT.PUT_LINE('Empleado: ' || V_FIRST);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No existe empleado con este ID');
END;
/

--2 EXCEPCIONES NO PREDEFINIDAS (POR EJEMPLO, violación de PK)
DECLARE
    JV_PK_VIOLATION EXCEPTION;
    PRAGMA EXCEPTION_INIT(JV_PK_VIOLATION, -1); --ASOCIADO A ORA-00001
BEGIN
    INSERT INTO JOBS VALUES ('AD_VP','Vice President', 10000, 15000);
EXCEPTION
    WHEN JV_PK_VIOLATION THEN
    DBMS_OUTPUT.PUT_LINE('Imposible introducir un JOB_ID que ya existe');
END;
/

