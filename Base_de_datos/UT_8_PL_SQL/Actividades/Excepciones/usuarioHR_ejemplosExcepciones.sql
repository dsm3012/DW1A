--4-CREAR EXCEPCIONES PROPIAS ASOCIANDO UN CÓDIGO DE ERROR 0RA-XXXXX
/*
CÓDIGOS RESERVADOS PARA DEFINIR ERRORES
?20000 y ?20999
PASOS:
1. DECLARAR UNA EXCEPCIÓN PROPIA
2. ASOCIARLA AL NÚMERO ORA ELEGIDO
3. LANZAR EL ERROR CON RAISE_APPLICATION_ERROR(-20xxx, 'mensaje')
4. capturarlo en la sección EXCEPTION
*/

--EJEMPLO:
DECLARE
    VIDE EMPLOYEES.EMPLOYEE_ID%TYPE:=100;
    VSAL EMPLOYEES.SALARY%TYPE;
    ESAL_MIN EXCEPTION;
    PRAGMA EXCEPTION_INIT(ESAL_MIN, -20050);

BEGIN
    SELECT SALARY INTO VSAL
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = VIDE;
    
    VSAL:= 500;
    --DEFINIMOS UNA REGLA
    IF VSAL < 1000 THEN
    --LANZAR NUESTRO ERROR
    RAISE_APPLICATION_ERROR (-20050, 'El salario no puede ser inferior a 1000');
    end if;
    -- en caso de que no haya error, actualizamos con el salario indicado al empleado seleccionado
    UPDATE EMPLOYEES SET SALARY = VSAL
    WHERE EMPLOYEE_ID = VIDE;
    DBMS_OUTPUT.PUT_LINE('Salario del empleado actualizado correctamente. Use COMMIT para confirmar cambios.');

EXCEPTION
    when esal_min then 
    DBMS_OUTPUT.PUT_LINE('ERROR ORA-20050: Salario inferior al mínimo permitido, no se actualizará');
END;
/

