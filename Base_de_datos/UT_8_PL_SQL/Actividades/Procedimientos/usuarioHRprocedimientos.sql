--AL SER EJECUTADO NOS MUESTRE EL NOMBRE DEL EMPLEADO CON EL ID BUSCADO E INTRODUCIDO COMO PARÁMETRO DEL PROCEDURE
--EXEC PR_NE(100); --> DEVUELVE Steven
CREATE OR REPLACE PROCEDURE PR_NE(PIDE IN EMPLOYEES.EMPLOYEE_ID%TYPE)
IS

 VNE EMPLOYEES.FIRST_NAME%TYPE;
BEGIN
    SELECT FIRST_NAME INTO VNE FROM EMPLOYEES WHERE EMPLOYEE_ID=PIDE;
    DBMS_OUTPUT.PUT_LINE('El empleado con ID '||PIDE||' es '||VNE);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No existe empleado con ID: '||PIDE);
END;
/

