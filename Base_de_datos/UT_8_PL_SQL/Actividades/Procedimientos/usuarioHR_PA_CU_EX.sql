--PROCEDIMIENTOS CON CURSORES
--USUARIO HR
SET SERVEROUTPUT ON;

DECLARE
--DECLARACIÓN DEL CURSOR:
 CURSOR CU_EMP IS
 SELECT FIRST_NAME, SALARY FROM EMPLOYEES WHERE SALARY < 6000 ORDER BY SALARY DESC;
--DECLARACIÓN DE VARIABLES
 NE EMPLOYEES.FIRST_NAME%TYPE;
 SE EMPLOYEES.SALARY%TYPE;
BEGIN
 DBMS_OUTPUT.PUT_LINE('Empleados con sueldo inferior a 6000:');
 DBMS_OUTPUT.PUT_LINE('_____________________________________');
 DBMS_OUTPUT.PUT_LINE('');
 
 OPEN CU_EMP;
 LOOP
    FETCH CU_EMP INTO NE, SE;
    EXIT WHEN CU_EMP%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE(RPAD(NE,15,' ') || LPAD(SE,10,' '));
 END LOOP;
CLOSE CU_EMP;
END;
/

