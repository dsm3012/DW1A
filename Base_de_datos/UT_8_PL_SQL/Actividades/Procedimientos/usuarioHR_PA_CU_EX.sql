CREATE OR REPLACE PROCEDURE PR_SALE(PSAL IN NUMBER)
AS
 CURSOR CU_EMP IS
 SELECT * FROM EMPLOYEES WHERE SALARY < PSAL ORDER BY SALARY DESC;
--DECLARACIÓN DE VARIABLES
 /*NE EMPLOYEES.FIRST_NAME%TYPE;
 SE EMPLOYEES.SALARY%TYPE;
 */
 VE CU_EMP%ROWTYPE;
BEGIN
 DBMS_OUTPUT.PUT_LINE('Empleados con sueldo inferior a: ' ||PSAL);
 DBMS_OUTPUT.PUT_LINE('_____________________________________');
 DBMS_OUTPUT.PUT_LINE('');
 
 OPEN CU_EMP;
    
 LOOP
    FETCH CU_EMP INTO VE;
    EXIT WHEN CU_EMP%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE(RPAD(VE.FIRST_NAME,15,' ') ||RPAD(VE.EMAIL,10,' ')|| LPAD(VE.SALARY,10,' '));
 END LOOP;
CLOSE CU_EMP;
END;
/

