--CONSULTAS DE VARRAY
--ACCEDER A LA POSICIÓN DE ELEMENTO EN UN VARRAY
--SELECT TELEFONOS PENDIENTE REVISION
--acceso NO permitido A TRAVÉS DE posición del array
SELECT
 P.NOMBRE,
 P.TELEFONOS(1),
 P.TELEFONOS(2)
FROM PERSONAS P;
/
--alternativa para acceso al varray de telefonos
--mediante una subconsulta
SELECT VALUE(P).NOMBRE,
VALUE(P).DIRECCION.CIUDAD,
(SELECT T.COLUMN_VALUE FROM TABLE(VALUE(P).TELEFONOS) T WHERE ROWNUM = 1) AS PRIMER_TELEFONO
FROM PERSONAS P;
/

--CONTAR LOS TELEFONOS
SELECT P.NOMBRE,
COUNT(*) AS TOTAL_TELEFONOS
FROM PERSONAS P,
TABLE(P.TELEFONOS) T
GROUP BY P.NOMBRE;
/

--ACCESO A LOS TELEFONOS DE PERSONAS (CADA TELEFONO EN UNA FILA)
SELECT P.NOMBRE,
 T.COLUMN_VALUE AS TELEFONO,
 ROW_NUMBER() OVER (PARTITION BY P.NOMBRE ORDER BY ROWNUM) AS POSICION_NUMERO_TELEFONO
FROM PERSONAS P,
 TABLE(P.TELEFONOS) T;
/

