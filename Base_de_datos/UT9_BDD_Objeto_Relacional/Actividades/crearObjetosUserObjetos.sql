--creación de tipos específicos de BDOR
--TIPOS DEFINIDOS POR EL USUARIO
--PUEDEN CONTENER ATRIBUTOS Y MÉTODOS 
--SINTAXIS:
CREATE TYPE DIRE_T AS OBJECT (
 CALLE VARCHAR2 (35),
 CIUDAD VARCHAR2 (20),
 CP NUMBER (5)
);
/

--TIPO EMPLEADO
CREATE TYPE EMP_T AS OBJECT (
 DNI VARCHAR2(9),
 NOMBRE VARCHAR2(50),
 SALARIO NUMBER,
 MEMBER FUNCTION SAL_ANUAL RETURN NUMBER
);
/

--CREACIÓN DEL CUERPO ASOCIADO AL MÉTODO
CREATE TYPE BODY EMP_T AS
 MEMBER FUNCTION SAL_ANUAL RETURN NUMBER IS
 BEGIN
  RETURN SALARIO *12;
 END;
END;
/

--COLECCIONES
--1._VARRAY (listas ordenadas de tamaño fijo)
CREATE TYPE TELEFONOS_T AS VARRAY(5) OF VARCHAR2(15);
/


--2._NESTED TABLE (se almacena en una tabla auxiliar, definir lista sin límite de tamaño)
CREATE TYPE AFICIONES_T AS TABLE OF VARCHAR2(30);
/

--CREACIÓN DE OBJETOS COMPLEJOS
--MODELAR ENTIDADES REALES COMBINANDO OBJETOS Y COLECCIONES
--TIPO PERSONA
CREATE TYPE PERSONA_T AS OBJECT(
 NOMBRE VARCHAR2(50),
 DIRECCION DIRE_T,
 TELEFONOS TELEFONOS_T,
 AFICIONES AFICIONES_T
);
/

--CREACIÓN DE TABLAS CON COLUMNAS QUE CONTIENEN OBJETOS
--CADA FILA REPRESENTA UN OBJETO EMP_T COMPLETO
CREATE TABLE EMP_OBJ OF EMP_T;
/

--TABLA RELACIONAL CON COLUMNA OBJETO
CREATE TABLE PEDIDOS (
 ID NUMBER PRIMARY KEY,
 FECHA DATE,
 DIRE_ENVIO DIRE_T
);
/

--TABLA CON COLECCIÓN
--PARA ALMACENAR LISTAS DINÁMICAS DE AFICIONES DE PERSONAS
CREATE TABLE PERSONAS OF PERSONA_T
 NESTED TABLE AFICIONES STORE AS AFICIONES_NT;
/

